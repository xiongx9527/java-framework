package com.xiongx9527.fw.plus.mybatis.datachange.dialect.it;

import com.xiongx9527.fw.plus.mybatis.datachange.dialect.OracleDataChangeDialect;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.util.Collections;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

class OracleDataChangeDialectIT extends DialectDatabaseContract {
	OracleDataChangeDialectIT() { super("DATACHANGE_ORACLE", new OracleDataChangeDialect()); }

	@Test
	void runsRealDatabaseContract() throws Exception { runContract(); }

	@Override protected boolean supportsCreatedSchema() { return false; }
	@Override protected String qualified(String schema, String table) { return '"' + table + '"'; }
	@Override protected String createTableSql(String table) {
		return "CREATE TABLE " + table + " (id NUMBER GENERATED BY DEFAULT AS IDENTITY UNIQUE, "
				+ "tenant_id NUMBER(19) NOT NULL, order_no VARCHAR2(40) NOT NULL, amount NUMBER(10) NOT NULL, "
				+ "status VARCHAR2(20) DEFAULT 'NEW', touched NUMBER(19) DEFAULT 0, "
				+ "PRIMARY KEY(tenant_id, order_no))";
	}
	@Override protected List<String> createTriggerSql(String schema, String table, String qualifiedTable) {
		return Collections.singletonList("CREATE TRIGGER \"trg_" + table + "\" BEFORE UPDATE ON "
				+ qualifiedTable + " FOR EACH ROW BEGIN :NEW.touched := :OLD.touched + 1; END;");
	}
	@Override protected String upsertSql(String table) {
		return "MERGE INTO " + table + " target USING (SELECT ? id, ? tenant_id, ? order_no, ? amount FROM dual) source "
				+ "ON (target.tenant_id=source.tenant_id AND target.order_no=source.order_no) "
				+ "WHEN MATCHED THEN UPDATE SET target.amount=source.amount "
				+ "WHEN NOT MATCHED THEN INSERT (id,tenant_id,order_no,amount) "
				+ "VALUES (source.id,source.tenant_id,source.order_no,source.amount)";
	}
	@Override protected String mergeSql(String table) {
		return "MERGE INTO " + table + " target USING (SELECT ? amount, ? tenant_id, ? order_no FROM dual) source "
				+ "ON (target.tenant_id=source.tenant_id AND target.order_no=source.order_no) "
				+ "WHEN MATCHED THEN UPDATE SET target.amount=source.amount";
	}
	@Override protected long insertAndGetGeneratedKey(Connection connection, String table) throws Exception {
		try (PreparedStatement insert = connection.prepareStatement("INSERT INTO " + table
				+ " (tenant_id,order_no,amount) VALUES (?,?,?)", new String[]{"ID"})) {
			insert.setLong(1, 7L);
			insert.setString(2, "A");
			insert.setInt(3, 10);
			assertThat(insert.executeUpdate()).isEqualTo(1);
			try (ResultSet keys = insert.getGeneratedKeys()) {
				assertThat(keys.next()).isTrue();
				long key = keys.getLong(1);
				assertThat(key).isPositive();
				return key;
			}
		}
	}
}
