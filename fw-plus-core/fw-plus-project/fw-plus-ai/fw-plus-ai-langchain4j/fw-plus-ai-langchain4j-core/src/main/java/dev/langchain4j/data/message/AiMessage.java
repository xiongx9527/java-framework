package dev.langchain4j.data.message;

import dev.langchain4j.Experimental;
import dev.langchain4j.agent.tool.ToolExecutionRequest;
import dev.langchain4j.data.image.Image;
import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;

import static dev.langchain4j.data.message.ChatMessageType.AI;
import static dev.langchain4j.internal.Utils.isNullOrEmpty;
import static dev.langchain4j.internal.Utils.quoted;
import static dev.langchain4j.internal.ValidationUtils.ensureNotBlank;
import static dev.langchain4j.internal.ValidationUtils.ensureNotEmpty;
import static dev.langchain4j.internal.ValidationUtils.ensureNotNull;
import static java.util.Arrays.asList;

/** Represents a message generated by a language model. */
public class AiMessage implements ChatMessage {

    public static final String GENERATED_IMAGES_KEY = "generated_images";

    private final String text;
    private final String thinking;
    private final List<ToolExecutionRequest> toolExecutionRequests;
    private final Map<String, Object> attributes;

    public AiMessage(String text) {
        this.text = ensureNotNull(text, "text");
        this.thinking = null;
        this.toolExecutionRequests = Collections.emptyList();
        this.attributes = Collections.emptyMap();
    }

    public AiMessage(List<ToolExecutionRequest> toolExecutionRequests) {
        this.text = null;
        this.thinking = null;
        this.toolExecutionRequests = immutableRequests(ensureNotEmpty(toolExecutionRequests, "toolExecutionRequests"));
        this.attributes = Collections.emptyMap();
    }

    public AiMessage(String text, List<ToolExecutionRequest> toolExecutionRequests) {
        this.text = ensureNotBlank(text, "text");
        this.thinking = null;
        this.toolExecutionRequests = immutableRequests(ensureNotEmpty(toolExecutionRequests, "toolExecutionRequests"));
        this.attributes = Collections.emptyMap();
    }

    public AiMessage(Builder builder) {
        this.text = builder.text;
        this.thinking = builder.thinking;
        this.toolExecutionRequests = immutableRequests(builder.toolExecutionRequests);
        this.attributes = immutableAttributes(builder.attributes);
    }

    public AiMessage withText(String text) {
        return builder().text(text).thinking(thinking)
                .toolExecutionRequests(toolExecutionRequests).attributes(attributes).build();
    }

    public String text() { return text; }

    @Experimental
    public String thinking() { return thinking; }

    @SuppressWarnings("unchecked")
    public List<Image> images() {
        Object images = attributes.get(GENERATED_IMAGES_KEY);
        return images == null ? Collections.<Image>emptyList() : (List<Image>) images;
    }

    public List<ToolExecutionRequest> toolExecutionRequests() { return toolExecutionRequests; }
    public boolean hasToolExecutionRequests() { return !isNullOrEmpty(toolExecutionRequests); }

    @Experimental
    public Map<String, Object> attributes() { return attributes; }

    @Experimental
    @SuppressWarnings("unchecked")
    public <T> T attribute(String key, Class<T> type) { return (T) attributes.get(key); }

    @Override public ChatMessageType type() { return AI; }

    @Override
    public boolean equals(Object object) {
        if (this == object) return true;
        if (object == null || getClass() != object.getClass()) return false;
        AiMessage that = (AiMessage) object;
        return Objects.equals(text, that.text) && Objects.equals(thinking, that.thinking)
                && Objects.equals(toolExecutionRequests, that.toolExecutionRequests)
                && Objects.equals(attributes, that.attributes);
    }

    @Override public int hashCode() { return Objects.hash(text, thinking, toolExecutionRequests, attributes); }

    @Override
    public String toString() {
        return "AiMessage { text = " + quoted(text) + ", thinking = " + quoted(thinking)
                + ", toolExecutionRequests = " + toolExecutionRequests + ", attributes = " + attributes + " }";
    }

    public Builder toBuilder() {
        return builder().text(text).thinking(thinking).toolExecutionRequests(toolExecutionRequests).attributes(attributes);
    }

    public static Builder builder() { return new Builder(); }

    public static class Builder {
        private String text;
        private String thinking;
        private List<ToolExecutionRequest> toolExecutionRequests;
        private Map<String, Object> attributes;

        public Builder text(String text) { this.text = text; return this; }
        @Experimental public Builder thinking(String thinking) { this.thinking = thinking; return this; }
        public Builder toolExecutionRequests(List<ToolExecutionRequest> requests) { this.toolExecutionRequests = requests; return this; }
        @Experimental public Builder attributes(Map<String, Object> attributes) { this.attributes = attributes; return this; }
        public AiMessage build() { return new AiMessage(this); }
    }

    public static AiMessage from(String text) { return new AiMessage(text); }
    public static AiMessage from(ToolExecutionRequest... requests) { return from(asList(requests)); }
    public static AiMessage from(List<ToolExecutionRequest> requests) { return new AiMessage(requests); }
    public static AiMessage from(String text, List<ToolExecutionRequest> requests) { return new AiMessage(text, requests); }
    public static AiMessage aiMessage(String text) { return from(text); }
    public static AiMessage aiMessage(ToolExecutionRequest... requests) { return aiMessage(asList(requests)); }
    public static AiMessage aiMessage(List<ToolExecutionRequest> requests) { return from(requests); }
    public static AiMessage aiMessage(String text, List<ToolExecutionRequest> requests) { return from(text, requests); }

    private static List<ToolExecutionRequest> immutableRequests(List<ToolExecutionRequest> requests) {
        return requests == null ? Collections.<ToolExecutionRequest>emptyList()
                : Collections.unmodifiableList(new ArrayList<ToolExecutionRequest>(requests));
    }

    private static Map<String, Object> immutableAttributes(Map<String, Object> attributes) {
        return attributes == null ? Collections.<String, Object>emptyMap()
                : Collections.unmodifiableMap(new LinkedHashMap<String, Object>(attributes));
    }
}
