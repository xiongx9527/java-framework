	@Test
	void ownerGuardMigrationRemovesHistoricalDuplicatesAndRejectsSecondOwner() throws Exception {
		DriverManagerDataSource dataSource = new DriverManagerDataSource(
				"jdbc:h2:mem:tiny_engine_owner_guard;MODE=MySQL;DB_CLOSE_DELAY=-1", "sa", "");
		JdbcTemplate jdbc = new JdbcTemplate(dataSource);
		jdbc.execute("create table t_permission_role (id int primary key, code varchar(255) not null, "
				+ "role_type varchar(60) not null)");
		jdbc.execute("create table r_auth_users_units_roles (id int generated by default as identity primary key, "
				+ "user_id int not null, unit_id int not null, unit_type varchar(60) not null, tenant_id int not null, "
				+ "role_id int not null)");
		jdbc.update("insert into t_permission_role(id, code, role_type) values "
				+ "(7, 'app_owner', 'app'), (4, 'app_admin', 'app')");
		jdbc.update("insert into r_auth_users_units_roles(user_id, unit_id, unit_type, tenant_id, role_id) values "
				+ "(1, 10, 'app', 9, 7), (2, 10, 'app', 9, 7), (3, 10, 'app', 9, 4)");

		execute(jdbc, read("META-INF/tiny-engine/sql/h2/update_table_2026_0811_owner_guard.sql"));
		execute(jdbc, read("META-INF/tiny-engine/sql/h2/update_table_2026_0811_owner_guard.sql"));

		assertThat(jdbc.queryForObject("select count(*) from r_auth_users_units_roles where unit_id = 10 "
				+ "and owner_guard = 1", Integer.class)).isEqualTo(1);
		assertThatThrownBy(() -> jdbc.update("insert into r_auth_users_units_roles"
				+ "(user_id, unit_id, unit_type, tenant_id, role_id, owner_guard) values (4, 10, 'app', 9, 7, 1)"))
				.isInstanceOf(org.springframework.dao.DataIntegrityViolationException.class);
		jdbc.update("insert into r_auth_users_units_roles"
				+ "(user_id, unit_id, unit_type, tenant_id, role_id, owner_guard) values (5, 10, 'app', 9, 4, null)");
	}

