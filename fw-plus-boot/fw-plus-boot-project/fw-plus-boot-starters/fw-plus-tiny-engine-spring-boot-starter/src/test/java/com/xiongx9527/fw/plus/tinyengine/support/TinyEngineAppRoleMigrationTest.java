	@Test
	void appRoleUpgradeIsIdempotentAndBackfillsOnlyCreatorsWithoutAnAppRole() throws Exception {
		DriverManagerDataSource dataSource = new DriverManagerDataSource(
				"jdbc:h2:mem:tiny_engine_app_roles;MODE=MySQL;DB_CLOSE_DELAY=-1", "sa", "");
		JdbcTemplate jdbc = new JdbcTemplate(dataSource);
		jdbc.execute("create table t_user (id int primary key, tenant_id int, username varchar(255))");
		jdbc.execute("create table t_app (id int primary key, tenant_id int, created_by int)");
		jdbc.execute("create table t_permission_role (id int generated by default as identity primary key, "
				+ "name varchar(255) not null, code varchar(255) not null unique, role_type varchar(60) not null, "
				+ "description varchar(2000), created_by varchar(60) not null, created_time timestamp not null, "
				+ "last_updated_by varchar(60) not null, last_updated_time timestamp not null)");
		jdbc.execute("create table r_auth_users_units_roles (id int generated by default as identity primary key, "
				+ "user_id int not null, unit_id int not null, unit_type varchar(60) not null, tenant_id int not null, "
				+ "role_id int not null, expired_time timestamp, created_by varchar(60) not null, "
				+ "created_time timestamp not null, last_updated_by varchar(60) not null, last_updated_time timestamp not null, "
				+ "constraint uq_app_user unique(user_id, unit_id, unit_type))");
		jdbc.update("insert into t_user(id, tenant_id, username) values "
				+ "(7, 9, 'owner'), (8, 9, 'admin'), (9, 9, 'existing-owner')");
		jdbc.update("insert into t_app(id, tenant_id, created_by) values (1, 9, 7), (2, 9, 8), (3, 9, 7)");
		jdbc.update("insert into t_permission_role(id, name, code, role_type, description, created_by, created_time, "
				+ "last_updated_by, last_updated_time) values "
				+ "(4, 'Tinybuilder_App_Admin', 'Tinybuilder_App_Admin', 'app', '', '1', current_timestamp, '1', current_timestamp), "
				+ "(5, 'Tinybuilder_App_Developer', 'Tinybuilder_App_Developer', 'app', '', '1', current_timestamp, '1', current_timestamp), "
				+ "(6, 'Tinybuilder_App_Owner', 'app_owner', 'app', '', '1', current_timestamp, '1', current_timestamp)");
		jdbc.update("insert into r_auth_users_units_roles(user_id, unit_id, unit_type, tenant_id, role_id, "
				+ "created_by, created_time, last_updated_by, last_updated_time) "
				+ "values (8, 2, 'app', 9, 4, '1', current_timestamp, '1', current_timestamp), "
				+ "(9, 3, 'app', 9, 6, '1', current_timestamp, '1', current_timestamp)");

		String migration = read("META-INF/tiny-engine/sql/h2/init_data_2026_0810_app_roles.sql");
		execute(jdbc, migration);
		execute(jdbc, migration);

		assertThat(jdbc.queryForObject("select count(*) from t_permission_role where code in "
				+ "('app_owner', 'app_admin', 'app_dev') and role_type = 'app'", Integer.class)).isEqualTo(3);
		assertThat(jdbc.queryForObject("select count(*) from r_auth_users_units_roles ur join t_permission_role pr "
				+ "on pr.id = ur.role_id where ur.unit_id = 1 and pr.code = 'app_owner'", Integer.class)).isEqualTo(1);
		assertThat(jdbc.queryForObject("select count(*) from r_auth_users_units_roles ur join t_permission_role pr "
				+ "on pr.id = ur.role_id where ur.unit_id = 2 and pr.code = 'app_owner'", Integer.class)).isZero();
		assertThat(jdbc.queryForObject("select count(*) from r_auth_users_units_roles ur join t_permission_role pr "
				+ "on pr.id = ur.role_id where ur.unit_id = 3 and pr.code = 'app_owner'", Integer.class)).isEqualTo(1);
	}

	@Test
	void mysqlAppRoleUpgradeMakesLegacyRolesPermanent() throws Exception {
		DriverManagerDataSource dataSource = new DriverManagerDataSource(
				"jdbc:h2:mem:tiny_engine_mysql_legacy_roles;MODE=MySQL;DB_CLOSE_DELAY=-1", "sa", "");
		JdbcTemplate jdbc = new JdbcTemplate(dataSource);
		jdbc.execute("create table t_user (id int primary key, tenant_id int, username varchar(255))");
		jdbc.execute("create table t_app (id int primary key, tenant_id int, created_by int, is_template boolean)");
		jdbc.execute("create table t_permission_role (id int generated by default as identity primary key, "
				+ "name varchar(255) not null, code varchar(255) not null unique, role_type varchar(60) not null, "
				+ "description varchar(2000), created_by varchar(60) not null, created_time timestamp not null, "
				+ "last_updated_by varchar(60) not null, last_updated_time timestamp not null)");
		jdbc.execute("create table r_auth_users_units_roles (id int generated by default as identity primary key, "
				+ "user_id int not null, unit_id int not null, unit_type varchar(60) not null, tenant_id int not null, "
				+ "role_id int not null, expired_time timestamp not null default current_timestamp, "
				+ "created_by varchar(60) not null, created_time timestamp not null, last_updated_by varchar(60) not null, "
				+ "last_updated_time timestamp not null, constraint uq_mysql_app_user unique(user_id, unit_id, unit_type))");
		jdbc.update("insert into t_user(id, tenant_id, username) values (1, 1, 'admin')");
		jdbc.update("insert into t_app(id, tenant_id, created_by, is_template) values (1, 1, 1, false)");
		jdbc.update("insert into t_permission_role(id, name, code, role_type, description, created_by, created_time, "
				+ "last_updated_by, last_updated_time) values "
				+ "(4, 'Tinybuilder_App_Admin', 'Tinybuilder_App_Admin', 'app', '', '1', current_timestamp, '1', current_timestamp), "
				+ "(5, 'Tinybuilder_App_Developer', 'Tinybuilder_App_Developer', 'app', '', '1', current_timestamp, '1', current_timestamp)");

		execute(jdbc, read("META-INF/tiny-engine/sql/mysql/init_data_2026_0810_app_roles.sql"));

		assertThat(jdbc.queryForObject("select expired_time from r_auth_users_units_roles where unit_type = 'app'",
				Object.class)).isNull();
		assertThat(jdbc.queryForObject("select count(*) from t_app a where exists (select 1 "
				+ "from r_auth_users_units_roles ur join t_permission_role pr on pr.id = ur.role_id "
				+ "where ur.tenant_id = a.tenant_id and ur.unit_id = a.id and ur.unit_type = 'app' "
				+ "and ur.user_id = 1 and (ur.expired_time is null or ur.expired_time > current_timestamp) "
				+ "and pr.role_type = 'app' and pr.code = 'app_owner')", Integer.class)).isEqualTo(1);
	}

	@Test
	void appEnableAppCodeAndPermissionRoleCodeMigrationsBackfillAndEnforceConstraints() throws Exception {
		DriverManagerDataSource dataSource = new DriverManagerDataSource(
				"jdbc:h2:mem:tiny_engine_app_role_migration_starter;MODE=MySQL;DB_CLOSE_DELAY=-1", "sa", "");
		JdbcTemplate jdbcTemplate = new JdbcTemplate(dataSource);
		jdbcTemplate.execute("create table t_tenant (id int primary key, enable boolean)");
		jdbcTemplate.update("insert into t_tenant(id, enable) values (1, null), (2, false)");
		jdbcTemplate.execute("create table t_app (id int primary key, enable boolean, code varchar(255))");
		jdbcTemplate.update("insert into t_app(id, enable, code) values (1, null, null), (2, false, null)");
		jdbcTemplate.execute("create table t_permission_role (id int primary key, name varchar(255) not null, "
				+ "role_type varchar(60) not null, code varchar(255))");
		jdbcTemplate.update("insert into t_permission_role(id, name, role_type, code) values "
				+ "(1, 'Tinybuilder_Admin', 'system', null), (2, 'Custom Role', 'app', null)");

		ClassPathResource resource = new ClassPathResource(
				"META-INF/tiny-engine/sql/h2/05_update_all_tables_ddl.sql");
		String migration;
		try (InputStream inputStream = resource.getInputStream()) {
			migration = StreamUtils.copyToString(inputStream, StandardCharsets.UTF_8);
		}
		for (String statement : migration.split(";")) {
			String sql = statement.trim();
			if (sql.isEmpty()) {
				continue;
			}
			boolean tenantStatement = (sql.startsWith("ALTER TABLE t_tenant") && sql.contains("enable"))
					|| sql.startsWith("UPDATE t_tenant SET enable");
			boolean appStatement = (sql.startsWith("ALTER TABLE t_app")
					&& (sql.contains("enable") || sql.contains("code")))
					|| sql.startsWith("UPDATE t_app SET enable")
					|| sql.startsWith("UPDATE t_app SET code")
					|| (sql.startsWith("CREATE UNIQUE INDEX") && sql.contains("app_code"));
			boolean roleStatement = (sql.startsWith("ALTER TABLE t_permission_role") && sql.contains("code"))
					|| sql.startsWith("UPDATE t_permission_role SET code")
					|| (sql.startsWith("CREATE UNIQUE INDEX") && sql.contains("permission_role_code"));
			if (tenantStatement || appStatement || roleStatement) {
				jdbcTemplate.execute(sql);
			}
		}

		assertThat(jdbcTemplate.queryForObject("select enable from t_tenant where id = 1", Boolean.class)).isTrue();
		assertThat(jdbcTemplate.queryForObject("select enable from t_tenant where id = 2", Boolean.class)).isFalse();
		assertThat(jdbcTemplate.queryForObject("select enable from t_app where id = 1", Boolean.class)).isTrue();
		assertThat(jdbcTemplate.queryForObject("select enable from t_app where id = 2", Boolean.class)).isFalse();
		assertThat(jdbcTemplate.queryForObject("select code from t_app where id = 1", String.class)).isEqualTo("app_1");
		assertThat(jdbcTemplate.queryForObject("select code from t_app where id = 2", String.class)).isEqualTo("app_2");
		assertThat(jdbcTemplate.queryForObject("select code from t_permission_role where id = 1",
				String.class)).isEqualTo("Tinybuilder_Admin");
		assertThat(jdbcTemplate.queryForObject("select code from t_permission_role where id = 2",
				String.class)).isEqualTo("role_2");
		assertThatThrownBy(() -> jdbcTemplate.update(
				"insert into t_tenant(id, enable) values (3, null)"))
				.isInstanceOf(org.springframework.dao.DataIntegrityViolationException.class);
		assertThatThrownBy(() -> jdbcTemplate.update(
				"insert into t_app(id, enable, code) values (3, null, null)"))
				.isInstanceOf(org.springframework.dao.DataIntegrityViolationException.class);
		assertThatThrownBy(() -> jdbcTemplate.update(
				"insert into t_app(id, enable, code) values (4, 1, 'app_1')"))
				.isInstanceOf(org.springframework.dao.DataIntegrityViolationException.class);
		assertThatThrownBy(() -> jdbcTemplate.update(
				"insert into t_permission_role(id, name, role_type, code) "
						+ "values (3, 'Duplicate', 'app', 'Tinybuilder_Admin')"))
				.isInstanceOf(org.springframework.dao.DataIntegrityViolationException.class);
	}

	private String read(String location) throws Exception {
		ClassPathResource resource = new ClassPathResource(location);
		try (InputStream inputStream = resource.getInputStream()) {
			return StreamUtils.copyToString(inputStream, StandardCharsets.UTF_8);
		}
	}

	private void execute(JdbcTemplate jdbc, String script) {
		for (String statement : script.split(";")) {
			String sql = statement.trim();
			if (!sql.isEmpty()) {
				jdbc.execute(sql);
			}
		}
	}
